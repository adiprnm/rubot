#!/usr/bin/env ruby
# frozen_string_literal: true

# Builds lib/rubot/web/assets/emoji.js — every emoji Unicode ships, each with
# the words an English speaker would search for it by.
#
# The picker needs the whole roster, and a roster of four thousand faces is not
# data to keep by hand: it is a table Unicode publishes. This script is how the
# table gets in, run whenever the data is refreshed:
#
#   ruby bin/build_emoji.rb
#
# Sources (cached in tmpdir after the first run, so a rebuild is offline):
#   * emoji-test.txt  — which sequences exist, their group, and whether they
#                       are "fully-qualified" (the form that renders as one
#                       picture; the other statuses are pieces of a sequence).
#   * CLDR annotations — the names and keywords, which is what a search types.
#
# Only the generated asset is committed. The sources are megabytes and the
# output is what the browser reads.

require "fileutils"
require "json"
require "net/http"
require "tmpdir"

EMOJI_TEST = "https://unicode.org/Public/emoji/latest/emoji-test.txt"
ANNOTATIONS = "https://raw.githubusercontent.com/unicode-org/cldr-json/main/" \
              "cldr-json/cldr-annotations-full/annotations/en/annotations.json"
ANNOTATIONS_DERIVED = "https://raw.githubusercontent.com/unicode-org/cldr-json/main/" \
                      "cldr-json/cldr-annotations-derived-full/annotationsDerived/en/annotations.json"

OUT = File.expand_path("../lib/rubot/web/assets/emoji.js", __dir__)
CACHE = ENV["RUBOT_EMOJI_CACHE"] || File.join(Dir.tmpdir, "rubot-emoji")

def fetch(url, name = File.basename(url))
  File.join(CACHE, name).tap do |path|
    next if File.file?(path) && File.size(path).positive?

    warn "fetching #{url}"
    FileUtils.mkdir_p(CACHE)
    body = Net::HTTP.get(URI(url))
    raise "empty response from #{url}" if body.nil? || body.empty?

    File.write(path, body)
  end.then { |path| File.read(path, encoding: "UTF-8") }
rescue StandardError => e
  abort "could not read #{url}: #{e.message}"
end

# The words that make a face findable. A name is the sentence a screen reader
# says out loud, so it is kept whole; the keywords are what nobody would think
# to type as a phrase, so they are flattened into plain words.
def words(annotation)
  return "" unless annotation.is_a?(Hash)

  name = Array(annotation["default"]).first.to_s
  keywords = Array(annotation["default"])[1..] || []
  [ name, *keywords ].join(" ")
                          .downcase
                          .gsub(/[^a-z0-9 ]+/, " ")
                          .squeeze(" ")
                          .strip
end

# cldr-json keeps the map under a key named after the download ("annotations",
# "annotationsDerived"), so the shape is unwrapped rather than guessed.
def annotation_map(url, name)
  json = JSON.parse(fetch(url, name))
  (json["annotations"] || json["annotationsDerived"]).fetch("annotations", {})
end

test = fetch(EMOJI_TEST)
annotations = annotation_map(ANNOTATIONS, "annotations.json")
derived = annotation_map(ANNOTATIONS_DERIVED, "annotationsDerived.json")
by_name = derived.merge(annotations) # exact names win over derived ones

# CLDR files the presentation-variant selector away (U+263A), while emoji-test
# lists the form that actually shows up on screen (U+263A U+FE0F). Both spellings
# are indexed so a face finds its words either way.
by_name = by_name.each_with_object({}) do |(name, annotation), index|
  index[name] = annotation
  index[name.delete("\uFE0F")] = annotation
end

version = test[/^# Version:\s*(\S+)/, 1].to_s

groups = []
current = nil

test.each_line do |line|
  if (m = line.match(/^# group:\s*(.+?)\s*$/))
    # "Component" is the skin tones and hair styles: parts of a face, not
    # faces. They are reachable through the sequences that use them.
    next if m[1] == "Component"

    current = [ m[1], [] ]
    groups << current
    next
  end

  next unless current
  next if line.start_with?("#")

  m = line.match(/^([0-9A-F ]+);\s*([a-z-]+)\s*#\s*(\S+)/)
  next unless m
  next unless m[2] == "fully-qualified"

  face = m[3]
  current[1] << (words(by_name[face] || by_name[face.delete("\uFE0F")]).then { |w| w.empty? ? face : "#{face} #{w}" })
end

total = groups.sum { |(_, faces)| faces.size }
payload = {
  "version" => version,
  "groups" => groups.map { |(name, faces)| [ name, faces ] }
}

File.write(OUT, <<~JS)
  // Every emoji Unicode ships, generated by bin/build_emoji.rb from
  // emoji-test.txt #{version} plus the CLDR English annotations. Do not edit by
  // hand: rebuild it with `ruby bin/build_emoji.rb` when the data moves on.
  //
  // One entry per face, "char words", where the words are the name and
  // keywords a search would type. Groups arrive in Unicode's own order and the
  // picker keeps it, so the roster reads the way the spec lists it.
  window.RUBOT_EMOJI = #{JSON.generate(payload)};
JS

puts "wrote #{OUT} (#{total} emoji, #{groups.size} groups, #{File.size(OUT)} bytes, v#{version})"
